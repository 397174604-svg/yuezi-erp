// 真实 ERP 客户状态 → 客户追踪页筛选桶（在住/签单/到访/线索）。
// ⚠ 必须先判签单再判在住：『已签合同但未入住』含子串『入住』，先判在住会误归在住桶。
export const STAGE = (s) => !s ? '线索'
  : ((s.includes('签合同') || s.includes('订房')) ? '签单'
    : (s.includes('入住') ? '在住'
      : (s.includes('意向') ? '到访' : '线索')));
